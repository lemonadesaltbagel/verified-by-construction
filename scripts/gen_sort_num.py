"""Generate lean/VWC/Tasks/SortNum.lean: the numeric layer of the sort-five-digits proof.

All interval endpoints are chosen here with exact rational arithmetic, and every per-step linear
check that Lean's `linarith` will be asked to close is first verified here (vertex enumeration
over the interval box), so the generated file is expected to compile without search.

Usage: python3 scripts/gen_sort_num.py > lean/VWC/Tasks/SortNum.lean
"""
from fractions import Fraction as F
import itertools
import math
import sys

EPS = F(2748779, 274877906944); G = F(11388943, 524288); B2 = F(3172863, 33554432)
SG = F(7614871, 33554432); OUT = F(2887801, 65536)


def mu(t): return F(2, 24) if t < 5 else (F(-1, 24) if t == 5 else F(t - 5, 24))
def Q(t): return F(452) if t < 5 else (F(451) if t == 5 else 452 + F(t - 5) ** 2)
def sd2(t): return Q(t) / 24 - mu(t) ** 2 + EPS


def sqb(x, q):
    v = math.sqrt(float(x)); lo = F(math.floor(v / float(q))) * q; hi = lo + q
    while lo * lo > x: lo -= q
    while hi * hi < x: hi += q
    return lo, hi


SD = {t: sqb(sd2(t), F(1, 10000)) for t in [0, 5, 6, 7, 8, 9]}
R24 = sqb(F(24), F(1, 100000))
GRID = {0: (F(195, 100), F(2)), 1: (F(21, 10), F(225, 100)), 2: (F(215, 100), F(235, 100)),
        3: (F(225, 100), F(25, 10)), 4: (F(23, 10), F(26, 10))}
TH = {0: (F(30, 100), F(96, 100)), 1: (F(39, 100), F(99, 100)), 2: (F(395, 1000), F(975, 1000)),
      3: (F(315, 1000), F(905, 1000)), 4: (F(195, 1000), F(80, 100))}
S2L, S2H = F(432, 100), F(454, 100)


def nuabs(t): return (1 - mu(t)) if t < 5 else (1 + mu(t))


def P(y): return 1 + y + y ** 2 / 2 + y ** 3 / 6 + y ** 4 / 24
def dn(x, d=4): return F(math.floor(x * 10 ** d), 10 ** d)
def up(x, d=4): return F(math.ceil(x * 10 ** d), 10 ** d)


RL = {k: dn(1 / (P(GRID[k][1] / 4) + (GRID[k][1] / 4) ** 5 * 6 / 600) ** 4) for k in range(5)}
RH = {k: up(1 / P(GRID[k][0] / 4) ** 4) for k in range(5)}
AL, AH, GL, GH = {}, {}, {}, {}
for k in range(5):
    AL[k] = dn(G / (SD[0][1] * (5 + (k + 1) * RH[k]))); AH[k] = up(G / (SD[0][0] * (5 + (k + 1) * RL[k])))
    for m in range(k + 1):
        GL[k, m] = dn(G * RL[k] / (SD[5 + m][1] * (5 + (k + 1) * RH[k])))
        GH[k, m] = up(G * RH[k] / (SD[5 + m][0] * (5 + (k + 1) * RL[k])))
    for m in range(k + 1):  # Delta enclosure
        n = 5 + k
        lo = 100 * nuabs(n) / (SD[n][1] * R24[1]) * (nuabs(0) / SD[0][1] + nuabs(5 + m) / SD[5 + m][1])
        hi = 100 * nuabs(n) / (SD[n][0] * R24[0]) * (nuabs(0) / SD[0][0] + nuabs(5 + m) / SD[5 + m][0])
        assert GRID[k][0] <= lo and hi <= GRID[k][1]
    # threshold checks over the whole interval box
    tl, th = TH[k]
    for verts in itertools.product((0, 1), repeat=k + 3):
        a = (AL[k], AH[k])[verts[0]]; s2 = (S2L, S2H)[verts[1]]
        g = {m: (GL[k, m], GH[k, m])[verts[2 + m]] for m in range(k + 1)}
        for e in range(10):
            for c in range(6):
                Z = (a * (c - F(5 * (e + 1), 12)) + sum(g[m] * ((1 if 1 <= m <= c else 0) - (e + 1) * mu(5 + m))
                                                       for m in range(k + 1)) - k + (e + 1) * B2 * s2)
                assert (Z < tl * SG * s2) if c <= k else (Z > th * SG * s2), (k, e, c)
        go9 = a * (5 - F(50, 12)) + sum(g[m] * ((1 if m >= 1 else 0) - 10 * mu(5 + m)) for m in range(k + 1))
        assert 0 <= go9 <= 1
    assert 1 + OUT * SG * tl < OUT * SG * (th - tl) and 1 + OUT * SG * (1 - th) < OUT * SG * (th - tl)


def q(x):
    x = F(x)
    return f"({x.numerator} / {x.denominator} : ℝ)" if x.denominator != 1 else f"({x.numerator} : ℝ)"


