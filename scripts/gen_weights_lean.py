"""Generate lean/VWC/Weights.lean from weights/parity.json.

Every float32 value is converted to its exact rational value (fractions.Fraction),
so the Lean constants are bit-for-bit the PyTorch parameters, not a transcription.

Usage: python3 scripts/gen_weights_lean.py weights/parity.json lean/VWC/Weights.lean
"""

from __future__ import annotations

import json
import sys
from fractions import Fraction

# (Lean field name, PyTorch parameter name, kind)
FIELDS = [
    ("tokEmb", "token_emb.weight", "mat"),
    ("posEmb", "pos_emb.weight", "mat"),
    ("Wq", "blocks.0.attn.W_q.weight", "mat"),
    ("Wk", "blocks.0.attn.W_k.weight", "mat"),
    ("Wv", "blocks.0.attn.W_v.weight", "mat"),
    ("Wo", "blocks.0.attn.W_o.weight", "mat"),
    ("W1", "blocks.0.mlp.fc1.weight", "mat"),
    ("b1", "blocks.0.mlp.fc1.bias", "vec"),
    ("W2", "blocks.0.mlp.fc2.weight", "mat"),
    ("b2", "blocks.0.mlp.fc2.bias", "vec"),
    ("Wh", "head.weight", "mat"),
]


def lit(x: float) -> str:
    q = Fraction(x)
    if q.denominator == 1:
        s = str(q.numerator)
    else:
        s = f"{q.numerator}/{q.denominator}"
    return f"({s})" if q < 0 or q.denominator != 1 else s


def main(src: str, dst: str) -> None:
    d = json.load(open(src))
    params, cfg = d["params"], d["meta"]["config"]
    V, D, F, L = cfg["vocab_size"], cfg["d_model"], cfg["d_ff"], cfg["max_seq_len"]
    used = {pt for _, pt, _ in FIELDS}
    assert used == set(params), f"unmapped parameters: {set(params) ^ used}"

    out = [
        "/-",
        "AUTO-GENERATED by scripts/gen_weights_lean.py from weights/parity.json. Do not edit.",
        f"Snapshot: {d['meta']['snapshot']}",
        f"Model: {d['meta']['model_shorthand_name']}; {d['meta']['n_params']} parameters, "
        f"{d['meta']['n_nonzero']} nonzero.",
        "Values are the exact rationals of the float32 parameters (PyTorch out x in layout).",
        "-/",
        "import VWC.Model",
        "",
        "namespace VWC",
        "",
        f"/-- The ParityFloorSubD3F9 parameters (vocab {V}, d_model {D}, d_ff {F}, max_seq_len {L}). -/",
        f"noncomputable def parityParams : Params {V} {D} {F} {L} where",
    ]
    for name, pt, kind in FIELDS:
        v = params[pt]["values"]
        if kind == "mat":
            rows = "; ".join(", ".join(lit(x) for x in row) for row in v)
            out.append(f"  {name} := !![{rows}]")
        else:
            out.append(f"  {name} := ![{', '.join(lit(x) for x in v)}]")
    out += ["", "end VWC", ""]
    open(dst, "w").write("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
